// Copies the markdown rules from the dodo repo (../dodo/public/md.js) into src/md.js, wrapped as a function so it needs neither vm nor eval:
// md.js is a classic script that expects the globals USERS, uid and LANG, which become the parameters.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const FROM = fileURLToPath(new URL(process.env.DODO_MD || '../../dodo/public/md.js', import.meta.url));
export const TO = fileURLToPath(new URL('../src/md.js', import.meta.url));
const names = 'parseBlock parseHeading serialize docPlan docText blockText splitDoc headingText headingItem ordKey'.split(' ');
// what src/md.js should be for this md.js (test/md.test.ts compares)
export const generate = src =>
  `// GENERATED by npm run md from dodo/public/md.js: do not edit, run the script again.\n// @ts-nocheck\nexport function loadMd(USERS, uid, LANG) {\n${src}\nreturn { ${names.join(', ')} };\n}\n`;

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(TO, generate(readFileSync(FROM, 'utf8')));
  console.log('src/md.js <-', FROM);
}
